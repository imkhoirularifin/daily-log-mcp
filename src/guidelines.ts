import {
  DIFFICULTY_LEVELS,
  FIXED_YESTERDAY,
  MIN_DATE_DISPLAY,
  WORKLOAD_BY_DIFFICULTY,
} from "./types.js";

export function getGuidelinesText(): string {
  const difficultyLines = DIFFICULTY_LEVELS.map(
    (d) => `  - "${d}" → beban_kerja ${WORKLOAD_BY_DIFFICULTY[d]}`,
  ).join("\n");

  return [
    "# Pedoman pengisian Daily Log (multi-user)",
    "",
    "## Identitas",
    "- Setiap API key terhubung ke satu user di database (nama + role).",
    "- `nama_anggota` dan `role` diisi otomatis dari user pemilik key — caller TIDAK boleh/tidak bisa set field ini.",
    `- yesterday (kolom fixed) selalu "${FIXED_YESTERDAY}" — jangan isi dari caller.`,
    "- User non-admin hanya melihat / mengubah / menghapus task miliknya sendiri.",
    "- User admin (mis. Dori sheet-sync) bisa list task semua user (filter opsional `nama_anggota`), dan memanggil `mark_synced`.",
    "- Non-admin tidak boleh memanggil `mark_synced`.",
    "",
    "## Alur kerja",
    "1. AI coding memanggil `add_task` / `add_tasks` dengan Bearer key user yang bersangkutan → task masuk inbox atas nama user tersebut.",
    "2. AI sync (admin key) memanggil `list_tasks` dengan `synced=false` (opsional filter `nama_anggota`), menyalin baris ke Google Sheets, lalu `mark_synced` dengan daftar id.",
    "3. Task yang sudah synced tidak bisa diubah/dihapus lewat `update_task` / `delete_task`.",
    "",
    "## Aturan baris (sheet)",
    "- Satu baris = satu task (jangan gabungkan beberapa pekerjaan dalam satu task).",
    `- Tanggal (tanggal) = hari pekerjaan dikerjakan, format DD/MM/YYYY.`,
    `- Pencatatan dimulai ${MIN_DATE_DISPLAY}. Tanggal sebelum itu ditolak.`,
    "",
    "## tingkat_kesulitan → beban_kerja (otomatis, jangan di-set caller)",
    difficultyLines,
    "",
    "## Default jika tidak diisi",
    "- progress = 100",
    '- status = "Done"',
    '- tiket_url = "-"',
    '- blocker = "-"',
    "",
    "## status yang diizinkan",
    '- "Done", "In Progress", "To Do", "Review"',
    "",
    "## sumber",
    "Wajib: nama AI/client yang menambahkan (contoh: \"Claude Desktop\", \"Cursor\", \"ChatGPT\").",
    "",
    "## Duplikat",
    "Jika tanggal + teks task sama dengan milik user yang sama, server memberi peringatan tetapi tetap menyimpan.",
    "",
    "## Tips untuk AI sheet-sync (admin)",
    "- Filter `synced=false` lalu tulis ke sheet dengan kolom lengkap dari output `list_tasks` (termasuk nama_anggota, role, yesterday, beban_kerja).",
    "- Setelah sukses tulis sheet, panggil `mark_synced` dengan semua id yang baru disalin.",
  ].join("\n");
}
